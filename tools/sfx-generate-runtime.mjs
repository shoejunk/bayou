// Compile the reviewed JSON recipes into C++ data without adding a JSON parser
// or network dependency to the game. Re-run after editing the source mappings.
import fs from 'node:fs';
const load=p=>JSON.parse(fs.readFileSync(p,'utf8').replace(/^\uFEFF/,''));
const manifest=load('assets/audio/sfx/manifest.json'),map=load('assets/audio/sfx/cue-map.json');
const q=JSON.stringify;
const f=n=>Number(n).toFixed(4)+'f';
const layers=a=>'{'+a.map(l=>`{${q(l.id)}, ${f(l.gain)}, ${f(l.at_seconds)}}`).join(',')+'}';
const definitions=manifest.masters.map(m=>`    {${q(m.id)}, ${q(m.wav.replace(/^assets\//,''))}, {${m.slices.map(s=>q(s.file.replace(/^assets\//,''))).join(',')}}, ${m.loop?'true':'false'}}`).join(',\n');
const profiles=map.profiles.map(p=>'    {'+[
 q(p.title), f(p.identity_pitch_semitones), layers(p.movement.layers),
 layers(p.deploy), layers(p.damage), layers(p.death),
 '{'+p.actions.map(a=>'{'+[q(a.name),q(a.internal_name),layers(a.layers)].join(', ')+'}').join(',')+'}'
].join(', ')+'}').join(',\n');
fs.writeFileSync('src/client/client_audio_data.inl',`// Generated by tools/sfx-generate-runtime.mjs from manifest.json and cue-map.json.\nconst std::vector<SoundDefinition>& definitions()\n{\n    static const std::vector<SoundDefinition> values = {\n${definitions}\n    };\n    return values;\n}\nconst std::vector<SoundProfile>& profiles()\n{\n    static const std::vector<SoundProfile> values = {\n${profiles}\n    };\n    return values;\n}\n`);
console.log(`Generated ${manifest.masters.length} sound definitions and ${map.profiles.length} card profiles.`);
